/** Permissions an admin may grant on an employee account. */
const ASSIGNABLE_EMPLOYEE_PERMISSIONS = [
  EMPLOYEE_PERMISSIONS.EMPLOYEE_DASHBOARD_VIEW,
  EMPLOYEE_PERMISSIONS.USER_VERIFICATION_VIEW,
  EMPLOYEE_PERMISSIONS.USER_VERIFICATION_RECOMMEND,
  EMPLOYEE_PERMISSIONS.USER_VERIFICATION_CORRECTION_REQUEST,
  EMPLOYEE_PERMISSIONS.PROPERTY_MODERATION_VIEW,
  EMPLOYEE_PERMISSIONS.PROPERTY_MODERATION_RECOMMEND,
  EMPLOYEE_PERMISSIONS.PROPERTY_MODERATION_CORRECTION_REQUEST,
  EMPLOYEE_PERMISSIONS.ENQUIRY_VIEW,
  EMPLOYEE_PERMISSIONS.ENQUIRY_UPDATE,
  EMPLOYEE_PERMISSIONS.CALL_NOTES_MANAGE,
  EMPLOYEE_PERMISSIONS.VISIT_VIEW,
  EMPLOYEE_PERMISSIONS.VISIT_UPDATE,
  EMPLOYEE_PERMISSIONS.FOLLOWUP_VIEW,
  EMPLOYEE_PERMISSIONS.FOLLOWUP_MANAGE,
  EMPLOYEE_PERMISSIONS.NOTIFICATIONS_VIEW,
  EMPLOYEE_PERMISSIONS.INTERNAL_NOTES_VIEW,
  EMPLOYEE_PERMISSIONS.INTERNAL_NOTES_MANAGE,
  EMPLOYEE_PERMISSIONS.REPORTS_VIEW,
  EMPLOYEE_PERMISSIONS.VIEW_UNASSIGNED_RECORDS,
];

function normalizeEmployeePermissions(permissions) {
  if (!Array.isArray(permissions)) return [];
  const allowed = new Set(ASSIGNABLE_EMPLOYEE_PERMISSIONS);
  return [...new Set(permissions.filter((p) => allowed.has(String(p))))];
}

module.exports = {
  EMPLOYEE_PERMISSIONS,
  ASSIGNABLE_EMPLOYEE_PERMISSIONS,
  normalizeEmployeePermissions,
};
